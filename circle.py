import math

def area(r):
    '''
    принимает int/float - r - радиус круга, возвращает площадь фигуры.
    Пример вызова area(5) = 78.5
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    принимает int/float - r - радиус круга, возвращает площадь фигуры.
    Пример вызова area(5) = 31.4
    '''
    return 2 * math.pi * r

