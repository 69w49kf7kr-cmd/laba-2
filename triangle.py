def area (a,h):
    '''
    принимает int/float - a и h - основание и высота треугольника, возвращает площадь фигуры.
     Пример вызова area(5,4) = 10
     '''
    return 0.5 * h * a

def perimeter (a,b,c):
    '''
    принимает int/float - a, b, c - три стороны треугольника, возвращает периметр фигуры.
    Пример вызова perimeter(5,5,5) = 15
    '''
    return a + b + c